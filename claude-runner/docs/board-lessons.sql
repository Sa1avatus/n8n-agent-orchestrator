-- AHAWR Board — lessons library table `board.lessons` (Postgres)
--
-- Design and field limits: claude-runner/docs/lessons.md ("Design: lessons library").
-- NOT APPLIED to any database.  Apply after claude-runner/docs/board-schema.sql
-- (it needs schema `board`).  All statements are idempotent, so this file can be
-- applied more than once.
--
-- `updated_at` is the optimistic-lock stamp, as board.providers uses it.
-- `version` is the entry format version from lessons.md, not the lock stamp.

CREATE TABLE IF NOT EXISTS board.lessons (
    id                                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission                           text NOT NULL CHECK (char_length(mission) <= 64),
    task_id                           text NOT NULL CHECK (char_length(task_id) <= 16),
    task_index                        integer NOT NULL CHECK (task_index BETWEEN 1 AND 999),
    kind                              text NOT NULL CHECK (kind IN ('fixed-after-retry', 'gave-up')),
    situation                         text NOT NULL CHECK (char_length(situation) <= 400),
    lesson                            text NOT NULL CHECK (char_length(lesson) <= 300),
    evidence                          jsonb NOT NULL CHECK (char_length(evidence::text) <= 1200),
    created_at                        timestamptz NOT NULL DEFAULT now(),
    status                            text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'retired')),
    times_shown                       integer NOT NULL DEFAULT 0 CHECK (times_shown >= 0),
    times_first_attempt_passed_after  integer NOT NULL DEFAULT 0
        CHECK (times_first_attempt_passed_after >= 0 AND times_first_attempt_passed_after <= times_shown),
    times_seen                        integer NOT NULL DEFAULT 1 CHECK (times_seen >= 1),
    version                           integer NOT NULL DEFAULT 1,
    updated_at                        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS lessons_mission_status_idx ON board.lessons (mission, status);

-- Which lesson was shown to which task. `first_attempt_passed` stays NULL until the task's
-- outcome is recorded, so an outcome is counted once.
CREATE TABLE IF NOT EXISTS board.lesson_shown (
    lesson_id             bigint NOT NULL REFERENCES board.lessons (id) ON DELETE CASCADE,
    mission               text NOT NULL CHECK (char_length(mission) <= 64),
    task_index            integer NOT NULL CHECK (task_index BETWEEN 1 AND 999),
    first_attempt_passed  boolean,
    PRIMARY KEY (lesson_id, mission, task_index)
);

CREATE INDEX IF NOT EXISTS lesson_shown_mission_task_idx ON board.lesson_shown (mission, task_index);

-- Board role grants, same shape as claude-runner/docs/board-role.sql.
-- Guarded: skipped when the role does not exist yet, so the file applies before the role.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'board_operator') THEN
        GRANT USAGE ON SCHEMA board TO board_operator;
        GRANT SELECT, INSERT, UPDATE, DELETE ON board.lessons TO board_operator;
        GRANT USAGE ON SEQUENCE board.lessons_id_seq TO board_operator;
        GRANT SELECT, INSERT, UPDATE, DELETE ON board.lesson_shown TO board_operator;
    END IF;
END
$$;
