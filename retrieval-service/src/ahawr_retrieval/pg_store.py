def translate(sql: str) -> str:
    """SQLite dialect used by ``Store`` and the indexer -> PostgreSQL."""
    match = _INSERT_OR.match(sql)
    if match:
        kind, table, cols, values = match.groups()
        columns = [c.strip() for c in cols.split(",")]
        keys = _PRIMARY_KEYS[table]
        updates = ", ".join(f"{c} = EXCLUDED.{c}" for c in columns if c not in keys)
        action = "DO NOTHING" if kind.upper() == "IGNORE" or not updates else f"DO UPDATE SET {updates}"
        sql = f"INSERT INTO {table}({cols}) VALUES ({values}) ON CONFLICT ({', '.join(keys)}) {action}"
    return sql.replace("%", "%%").replace("?", "%s")


def mapu(text: str) -> str:
    """Keep identifiers with underscores in one lexeme (see the module docstring)."""
    return text.replace("_", "zqz")


def tsquery_from_match(match_query: str) -> str:
    """FTS5 ``"a" OR "b"`` (see service.fts_match_query) -> ``a | b`` for ``to_tsquery``."""
    terms: list[str] = []
    for raw in _TERM.findall(match_query):
        for word in re.findall(r"\w+", mapu(raw.replace('""', '"')), flags=re.UNICODE):
            if word not in terms:
                terms.append(word)
    return " | ".join(terms)


def _clean(params: Sequence[Any] | None) -> list[Any] | None:
    """PostgreSQL text cannot hold NUL bytes (SQLite stores them): drop them from every string parameter."""
    if not params:
        return None
    return [p.replace(chr(0), "") if isinstance(p, str) else p for p in params]


class _Cursor:
    def __init__(self, cursor: Any) -> None:
        self._cursor = cursor
        self.rowcount = cursor.rowcount

    def fetchall(self) -> list[dict[str, Any]]:
        return list(self._cursor.fetchall()) if self._cursor.description else []

    def fetchone(self) -> dict[str, Any] | None:
        return self._cursor.fetchone() if self._cursor.description else None


class _Connection:
    """The part of the sqlite3 connection API that Store and the indexer use."""

    def __init__(self, raw: Any) -> None:
        self._raw = raw

    def execute(self, sql: str, params: Sequence[Any] | None = None) -> _Cursor:
        return _Cursor(self._raw.execute(translate(sql), _clean(params)))

    def executemany(self, sql: str, rows: Iterable[Sequence[Any]]) -> None:
        data = [_clean(r) or [] for r in rows]
        if data:
            with self._raw.cursor() as cursor:
                cursor.executemany(translate(sql), data)


class PgStore(Store):
    """PostgreSQL store with the interface of ``Store``. Writes go through one connection (``lock``), reads through another."""

    def __init__(self, dsn: str, schema: str = "retrieval") -> None:
        import psycopg
        from psycopg.rows import dict_row

        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", schema):
            raise ValueError(f"invalid schema name {schema!r}")
        self.path = dsn
        self.schema = schema
        self.lock = threading.RLock()
        self._read_lock = threading.RLock()
        self._write = psycopg.connect(dsn, autocommit=True, row_factory=dict_row)
        self._read = psycopg.connect(dsn, autocommit=True, row_factory=dict_row)
        with self.lock:
            self._write.execute("SELECT pg_advisory_lock(%s)", [_ADVISORY_LOCK])
            try:
                self._write.execute(f"CREATE SCHEMA IF NOT EXISTS {schema}")
                self._write.execute(f"SET search_path TO {schema}")
                for statement in _DDL:
                    self._write.execute(statement)
                self._write.execute(
                    "INSERT INTO meta(key, value) VALUES ('schema_version', %s) ON CONFLICT (key) DO NOTHING",
                    [str(SCHEMA_VERSION)],
                )
            finally:
                self._write.execute("SELECT pg_advisory_unlock(%s)", [_ADVISORY_LOCK])
        self._read.execute(f"SET search_path TO {schema}")

    def close(self) -> None:
        with self.lock:
            self._write.close()
        with self._read_lock:
            self._read.close()

    @contextmanager
    def transaction(self) -> Iterator[_Connection]:  # type: ignore[override]
        with self.lock:
            self._write.execute("BEGIN")
            try:
                yield _Connection(self._write)
            except BaseException:
                self._write.execute("ROLLBACK")
                raise
            self._write.execute("COMMIT")

    def _query(self, sql: str, params: Sequence[Any] = ()) -> list[Any]:
        with self._read_lock:
            return _Connection(self._read).execute(sql, params).fetchall()

    # ----------------------------------------------------------------- chunks

    @staticmethod
    def _fts_row(conn: _Connection, chunk_id_row: int, fts: tuple[str, str, str]) -> None:
        body, symbols, path = (mapu(part) for part in fts)
        conn.execute(
            "INSERT INTO chunks_fts(id, tsv) VALUES (?, "
            "setweight(to_tsvector('english', ?), 'D') || setweight(to_tsvector('english', ?), 'B') "
            "|| setweight(to_tsvector('english', ?), 'C')) "
            "ON CONFLICT (id) DO UPDATE SET tsv = EXCLUDED.tsv",
            (chunk_id_row, body, symbols, path),
        )

    @staticmethod
    def insert_chunk(conn: _Connection, record: ChunkRecord, fts: tuple[str, str, str]) -> int:  # type: ignore[override]
        values = [getattr(record, c.strip()) for c in _CHUNK_COLUMNS.split(",")][1:]
        row = conn.execute(
            f"INSERT INTO chunks({_CHUNK_COLUMNS.split(', ', 1)[1]}) "
            f"VALUES ({_placeholders(len(values))}) RETURNING id",
            values,
        ).fetchone()
        assert row is not None
        rowid = int(row["id"])
        if record.status == ACTIVE:
            PgStore._fts_row(conn, rowid, fts)
        return rowid

    @staticmethod
    def replace_chunk(  # type: ignore[override]
        conn: _Connection, record: ChunkRecord, fts: tuple[str, str, str] | None
    ) -> None:
        columns = [c.strip() for c in _CHUNK_COLUMNS.split(",")][2:]
        sets = ", ".join(f"{c} = ?" for c in columns)
        conn.execute(
            f"UPDATE chunks SET {sets} WHERE id = ?",
            (*(getattr(record, c) for c in columns), record.id),
        )
        if fts is not None:
            conn.execute("DELETE FROM chunks_fts WHERE id = ?", (record.id,))
            if record.status == ACTIVE:
                PgStore._fts_row(conn, record.id, fts)

    @staticmethod
    def deactivate_chunk(  # type: ignore[override]
        conn: _Connection, record: ChunkRecord, status: str, reason: str, generation: int
    ) -> None:
        import time

        conn.execute(
            "UPDATE chunks SET status = ?, status_reason = ?, generation = ?, updated_at = ? WHERE id = ?",
            (status, reason, generation, time.time(), record.id),
        )
        conn.execute("DELETE FROM chunks_fts WHERE id = ?", (record.id,))

    # ----------------------------------------------------------------- search

    def lexical_search(
        self,
        match_query: str,
        corpora: Sequence[str],
        source_types: Sequence[str],
        limit: int,
        restrict_chunk_ids: Sequence[str] | None = None,
    ) -> list[tuple[str, float]]:
        query = tsquery_from_match(match_query)
        if not query or not corpora or not source_types:
            return []
        sql = (
            "SELECT c.chunk_id AS chunk_id, ts_rank_cd(f.tsv, q.query, 1) AS score "
            "FROM chunks_fts f JOIN chunks c ON c.id = f.id, to_tsquery('english', ?) AS q(query) "
            f"WHERE f.tsv @@ q.query AND c.corpus_id IN ({_placeholders(len(corpora))}) "
            f"AND c.source_type IN ({_placeholders(len(source_types))}) AND c.status = 'active'"
        )
        params: list[Any] = [query, *corpora, *source_types]
        if restrict_chunk_ids is not None:
            if not restrict_chunk_ids:
                return []
            sql += f" AND c.chunk_id IN ({_placeholders(len(restrict_chunk_ids))})"
            params.extend(restrict_chunk_ids)
        sql += " ORDER BY score DESC LIMIT ?"
        params.append(limit)
        try:
            rows = self._query(sql, params)
        except Exception:  # a malformed tsquery must not fail the whole retrieval, as with FTS5
            return []
        return [(r["chunk_id"], float(r["score"])) for r in rows]
