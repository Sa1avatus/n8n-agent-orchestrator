"""PostgreSQL-backed index store (optional). SQLite (``store.Store``) stays the default and the built-in fallback.

Enabled by ``RETRIEVAL_DATABASE_URL`` (psycopg DSN) and, optionally, ``RETRIEVAL_DATABASE_SCHEMA`` (default ``retrieval``).
It implements the same interface as ``Store`` by subclassing it: everything that is plain SQL is inherited and reaches PostgreSQL through
a thin dialect shim (``?`` placeholders, ``INSERT OR REPLACE/IGNORE``); what differs is overridden here:

* full-text search: SQLite FTS5 ``chunks_fts`` (bm25, porter) -> a ``chunks_fts(id, tsv tsvector)`` table with a GIN index and
  ``ts_rank_cd`` (``english`` configuration, weights body 0.1 : path 0.2 : symbols 0.4, the 1 : 2 : 4 of the bm25 call). Underscores are
  mapped to ``zqz`` on both sides, because the PostgreSQL parser splits ``parse_invoice`` while FTS5 (tokenchars '_') keeps it whole.
* ``AUTOINCREMENT`` ids -> identity columns with ``RETURNING``; BLOB -> BYTEA; REAL -> DOUBLE PRECISION.
* a second connection serves reads, so a long indexing transaction does not block retrieval (MVCC); writes stay serialised by ``lock``.

The vector index is still the in-memory ``VectorIndex`` filled from ``embeddings`` (pgvector is not required).
"""

